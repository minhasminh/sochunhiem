// Khởi tạo 32 ghế và xếp trước 31 học sinh theo 4 dãy tương ứng 4 tổ
export const generateDefaultSeats = (
  studentsList: Student[],
  columns = 4,
  rows = 4,
  seatsPerDesk = 2
): DeskSeat[] => {
  const seats: DeskSeat[] = [];

  // Nhóm học sinh theo tổ để xếp vào các dãy tương ứng
  // Dãy 1: Tổ 1; Dãy 2: Tổ 2; Dãy 3: Tổ 3; Dãy 4: Tổ 4
  const studentsByGroup: Record<number, Student[]> = { 1: [], 2: [], 3: [], 4: [] };
  studentsList.forEach((st) => {
    const g = st.groupNumber >= 1 && st.groupNumber <= 4 ? st.groupNumber : 1;
    studentsByGroup[g].push(st);
  });

  const assignedStudentIds = new Set<string>();

  for (let c = 1; c <= columns; c++) {
    const groupStudents = studentsByGroup[c] || [];
    let studentIndex = 0;

    for (let r = 1; r <= rows; r++) {
      for (let s = 1; s <= seatsPerDesk; s++) {
        let studentId: string | null = null;
        if (studentIndex < groupStudents.length) {
          studentId = groupStudents[studentIndex].id;
          assignedStudentIds.add(studentId);
          studentIndex++;
        }

        seats.push({
          id: `seat-c${c}-r${r}-s${s}`,
          column: c,
          row: r,
          seatNumber: s,
          studentId,
        });
      }
    }
  }

  // Đảm bảo mọi học sinh chưa có chỗ (nếu có dư từ nhóm) được xếp vào chỗ trống còn lại
  const unassigned = studentsList.filter((st) => !assignedStudentIds.has(st.id));
  let unassignedIdx = 0;
  for (const seat of seats) {
    if (!seat.studentId && unassignedIdx < unassigned.length) {
      seat.studentId = unassigned[unassignedIdx].id;
      unassignedIdx++;
    }
  }

  return seats;
};

